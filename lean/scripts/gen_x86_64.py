def emit_routines(source: str, config: RoutineConfig):
    """Emit a source routine, plus its helper when repeated rounds are factored."""
    routine = emit_routine(source, config)
    return factor_mul_rounds(routine) if config.lean_name == "mulMont" else [routine]


def transcribe(source: str, config: RoutineConfig) -> str:
    """Render one x86-64 source routine and any validated factored helpers."""
    routines = emit_routines(source, config)
    return "\n".join(routine.text(comment_column([routine])) for routine in routines)


def gen_program(source: Optional[str] = None, invert_source: Optional[str] = None) -> str:
    routines = all_routines(source, invert_source)
    return HEADER + "\n".join(
        routine.text(comment_column([routine])) for routine in routines
    ) + FOOTER


def in_contract(op: str, field: str, operands: Sequence[int]) -> bool:
    """Whether a row satisfies both the public and x86-64 backend assertions."""
    if not gen.in_public_contract(op, field, operands):
        return False
    # Unlike AArch64, the x86-64 multiplication backend itself additionally
    # debug-asserts a canonical rhs, even when the public contract accepted a
    # canonical lhs with an arbitrary rhs.
    return op != "MUL" or gen.is_canonical(field, operands[1])


